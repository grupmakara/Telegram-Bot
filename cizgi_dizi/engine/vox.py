"""Commercial-safe voice-over with VoxCPM2 (Apache-2.0).

Each character gets an original voice designed from a text description (no real
person's voice is cloned). The designed clip is saved once as
diziler/<dizi>/sesler/<character>.wav and every line is then generated by
cloning that clip, with an English emotion cue from the line's mood. Every line
is checked with Whisper and regenerated (up to 4 tries) if it does not match.

  python3 engine/vox.py design diziler/<dizi>            # create missing character voices
  python3 engine/vox.py voice diziler/<dizi>/bolumler/bolumNN.json [...] [--force|--fix]

Clips go to seslendirme/<dizi>/vox/<bolumNN>/s<scene>_l<line>.wav; render.py
prefers them over older takes.
"""
import json
import subprocess
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from clone import check  # noqa: E402  (Whisper word-level check + tail cut)
from voices import clip_name, spoken_lines  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

VOICE_DESIGN = {
    "riza": "A 70-year-old Turkish man, warm, slightly husky, calm and wise voice",
    "zeynep": "A 27-year-old Turkish woman, soft, clear and warm voice, gentle and emotional",
    "selma": "A 50-year-old elegant upper-class Istanbul woman, sharp, haughty and confident voice",
    "kenan": "A 55-year-old Turkish man, nervous, fast-talking, slightly nasal bureaucrat voice",
    "can": "A 25-year-old Turkish man, friendly, energetic and sincere young voice",
    "ferit": "A 40-year-old Turkish man, smooth, deep, cold and cunning voice",
    "hoca": "A 60-year-old Turkish professor, deep, articulate and measured voice",
    "anlatici": "A Turkish male narrator, deep, cinematic and mysterious storytelling voice",
    "usta": "A 75-year-old Turkish craftsman, gravelly, kind and folksy voice",
    "hakan": "A 55-year-old Turkish businessman, calm, deep and emotional voice",
    "murat": "A 33-year-old Turkish civil servant, clear, confident and warm voice",
    "tarik": "A 60-year-old powerful Turkish tycoon, very deep, slow and menacing voice",
    "hirsiz": "A 30-year-old Turkish man, rough street voice, aggressive and edgy",
}
DESIGN_TEXT = {
    "default": "Bu apartmanda yıllardır yaşıyorum. Herkesi tanırım, her sırrı bilirim. Ama bugün her şey değişecek.",
}
MOOD_CUE = {
    "angry": "angry, raised voice", "sad": "sad, quiet, emotional", "surprised": "shocked, surprised",
    "worried": "worried, nervous", "smug": "smug, sarcastic", "smile": "warm, smiling", "neutral": "calm",
}
_model = None


def model():
    global _model
    if _model is None:
        from voxcpm import VoxCPM
        _model = VoxCPM.from_pretrained("openbmb/VoxCPM2", load_denoiser=False)
    return _model


def save(wav, out):
    sr = model().tts_model.sample_rate
    a = np.asarray(wav, dtype=np.float32)
    subprocess.run(["ffmpeg", "-v", "quiet", "-y", "-f", "f32le", "-ar", str(sr), "-ac", "1", "-i", "-",
                    "-ar", "48000", str(out)], input=a.tobytes(), check=True)


def voice_dir(dizi):
    return ROOT / "diziler" / dizi / "sesler"


def design(dizi):
    d = voice_dir(dizi)
    d.mkdir(parents=True, exist_ok=True)
    for who, desc in VOICE_DESIGN.items():
        out = d / f"{who}.wav"
        if out.exists():
            continue
        text = DESIGN_TEXT.get(who, DESIGN_TEXT["default"])
        best = None
        for _ in range(3):
            tmp = d / f".{who}.try.wav"
            save(model().generate(text=f"({desc}){text}", cfg_value=2.0, inference_timesteps=10), tmp)
            score, heard, _ = check(tmp, text)
            if best is None or score > best[0]:
                if best:
                    best[1].unlink(missing_ok=True)
                keep = d / f".{who}.best.wav"
                tmp.replace(keep)
                best = (score, keep, heard)
            if score >= 0.95:
                break
        best[1].replace(out)
        (d / f"{who}.txt").write_text(text + "\n")
        print(f"ses tasarlandı: {who:8} {best[0]:.2f} | {best[2]}", flush=True)


def voice_episode(ep_path, force=False, fix=False):
    ep_path = Path(ep_path)
    dizi = ep_path.parent.parent.name
    ep = json.loads(ep_path.read_text(encoding="utf-8"))
    out_dir = ROOT / "seslendirme" / dizi / "vox" / ep_path.stem
    out_dir.mkdir(parents=True, exist_ok=True)
    for si, li, ln in spoken_lines(ep):
        out = out_dir / clip_name(si, li)
        meta = out_dir / f"{clip_name(si, li)}.txt"
        if out.exists() and not force:
            if not (fix and meta.exists() and float(meta.read_text().split()[0]) < 0.9):
                continue
        ref = voice_dir(dizi) / f"{ln['who']}.wav"
        text = ln.get("say", ln["text"])
        cue = MOOD_CUE.get(ln.get("mood", "neutral"), "calm")
        if ln["who"] == "anlatici":
            cue = "dramatic, mysterious"
        best = None
        for attempt in range(4):
            tmp = out_dir / f".try{attempt}.wav"
            save(model().generate(text=f"({cue}){text}", reference_wav_path=str(ref), cfg_value=2.0,
                                  inference_timesteps=10), tmp)
            score, heard, cut = check(tmp, text)
            if best is None or score > best[0]:
                best = (score, tmp, heard, cut)
            if score >= 0.9:
                break
        score, tmp, heard, cut = best
        if cut:
            subprocess.run(["ffmpeg", "-v", "quiet", "-y", "-i", str(tmp), "-t", f"{cut:.2f}",
                            "-af", "afade=t=out:st=%.2f:d=0.12" % max(0, cut - 0.12), str(out)], check=True)
        else:
            tmp.replace(out)
        for f in out_dir.glob(".try*.wav"):
            f.unlink()
        meta.write_text(f"{score:.3f} {heard}\n")
        flag = "  " if score >= 0.9 else "!!"
        print(f"{flag} {ep_path.stem}/{out.name} {ln['who']:8} {score:.2f} | {heard}", flush=True)


if __name__ == "__main__":
    cmd, *rest = sys.argv[1:]
    paths = [a for a in rest if not a.startswith("--")]
    if cmd == "design":
        design(Path(paths[0]).name)
    elif cmd == "voice":
        for p in paths:
            voice_episode(p, "--force" in rest, "--fix" in rest)
